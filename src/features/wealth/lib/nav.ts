/**
 * 净值序列的**展示顺序**规则（2026-11-09 用户要求「净值 tab 表格按时间逆序，最新在第一行」）。
 *
 * ## 为什么单独抽出来，而不是在页面里写一句 `.reverse()`
 *
 * 同一份净值数组在本页有**三种消费者，要求相反的顺序**：
 *
 * | 消费者 | 要的顺序 | 为什么 |
 * |---|---|---|
 * | 折线图 | **正序** | 时间轴只能从左到右，逆序会把曲线左右翻转 |
 * | 最大回撤 | **正序** | 逐点递推（`peak` 累积），逆序算出来的不是回撤 |
 * | 末值徽章 | **正序** | 取 `at(-1)`，逆序会取到最早那天 |
 * | 明细表格 | **逆序** | 读者关心「最新一行」，不该先滚过 30 行历史 |
 *
 * 于是「逆序」是**一个视图选择**，不是数据重算 —— 指标仍然全部由后端算好。
 * 把它收成一个函数，一是避免有人顺手 `navRows.reverse()` 把原数组改掉
 * （`reverse()` 是原地修改，会让图表和回撤一起错），二是这条规则能被测试锁住。
 *
 * ⛔ 不要在这里做任何数值计算（累计、年化、回撤）：前端只显示，不重算。
 */
export function navRowsDesc<T extends { trade_date: string }>(rows: readonly T[]): T[] {
  // ⛔ 必须复制后排序：[...rows] 保证调用方数组不被就地修改
  return [...rows].sort((a, b) => b.trade_date.localeCompare(a.trade_date))
}
